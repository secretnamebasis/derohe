// wolfPermuteAVX2Asm applies a 4-symbol applySubOp sequence (see
// branch_op_subops_gen_test.go) to step_3[pos1:pos1+32], broadcasting
// pos2byte, then writes back only the first n bytes (n = pos2-pos1),
// leaving the rest of the 32-byte window unchanged via a blend -- matching
// applyBranchOp's [pos1,pos2) semantics exactly. Caller must guarantee
// pos1+32 <= len(step_3); see the Go wrapper's bounds check.
//
// Fully unrolled (no CALL/RET in the per-op dispatch): the earlier
// subroutine-call-based version measured statistically indistinguishable
// from no-AVX2-at-all (~0.45% on 20x50-rep benchstat, well inside the ~1%
// CI), and the CALL/RET chain through applyOneSubOp -> rolInplace ->
// srlInplace -> reverse8Inplace (up to 6 nested calls for a single
// rotate-based sub-op) was the leading suspect. This version inlines every
// primitive at every one of the 4 sequence positions directly -- same
// verified logic as the call-based version, just flattened -- to isolate
// whether call overhead was actually the cause.
//
// func wolfPermuteAVX2Asm(data *byte, seq *[4]byte, pos2byte byte, n uint64)
